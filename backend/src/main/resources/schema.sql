-- Creates our tables. Spring Boot runs this file at startup (spring.sql.init.mode=always).
-- "IF NOT EXISTS" means running it again does nothing, so existing data is kept.

-- ---------------------------------------------------------------------------
-- events: one row per career event.
-- NOTE FOR MERGING: a teammate building GET/POST /events may also define this table.
-- Column names follow Interface Contract v1. Combine into ONE definition when merging.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- the database picks the next id
    event_title      VARCHAR(200) NOT NULL,
    host             VARCHAR(200) NOT NULL,
    event_date       DATE         NOT NULL,   -- "date" and "time" are SQL type names, so we prefix them
    event_time       TIME         NOT NULL,
    location         VARCHAR(200) NOT NULL,
    category         VARCHAR(50)  NOT NULL,
    audience         VARCHAR(500) NOT NULL,
    format           VARCHAR(50)  NOT NULL,
    register_link    VARCHAR(500),            -- optional, can be NULL
    capacity         INT          NOT NULL DEFAULT 0, -- 0 = unlimited
    registered_count INT          NOT NULL DEFAULT 0,
    -- Safety nets: the database itself refuses impossible numbers.
    CHECK (capacity >= 0),
    CHECK (registered_count >= 0),
    CHECK (capacity = 0 OR registered_count <= capacity)
);

-- ---------------------------------------------------------------------------
-- registrations: one row per "student X registered for event Y".
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS registrations (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id   BIGINT    NOT NULL REFERENCES events(id) ON DELETE CASCADE, -- must be a real event; deleting the event deletes its registrations
    user_id    BIGINT    NOT NULL,            -- the user's id from Shared Core (their table, not ours)
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (event_id, user_id)                -- the same student can't register twice for one event
);
