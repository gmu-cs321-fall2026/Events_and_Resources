-- SQL WORDS YOU'LL SEE A LOT
--   BIGINT        a whole number (used for ids)
--   INT           a smaller whole number (used for counts)
--   VARCHAR(n)    text, at most n characters long
--   DATE / TIME   a calendar date (2026-10-28) / a time of day (17:30)
--   TIMESTAMP     a date AND a time together
--   NOT NULL      this column can't be left empty
--   UNIQUE        no two rows can have the same value in this column
--   PRIMARY KEY   the column that identifies each row (no two rows share it)
--   REFERENCES    "this value must exist in another table" (called a foreign key)
--   DEFAULT x     if nobody gives a value, use x
--   CHECK (...)   a rule every row must follow, or the database refuses it
--   --            starts a comment; SQL ignores everything after it on that line


-- Creates our tables. Spring Boot runs this file at startup (spring.sql.init.mode=always).
-- "IF NOT EXISTS" means running it again does nothing, so existing data is kept.

--  ORDER MATTERS: a table can only point at (REFERENCES) a table created ABOVE it.
--   categories, audiences  ->  events  ->  event_audiences, registrations  ->  (Jean: resources, opportunities)
-- ---------------------------------------------------------------------------
-- LOOKUP TABLES (from the ER diagram: Events "has" Category, "has" Audience)
-- A lookup table is a short, fixed list of allowed values. Other tables point at it,
-- so the database itself refuses a value that isn't on the list.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- the database picks the next id
    name VARCHAR(50) NOT NULL UNIQUE,  -- e.g. "Workshop". UNIQUE: no two rows with the same name,
                                      -- and it lets events.category point at this column
    description VARCHAR(500)  --can take away just so we can have description
);

CREATE TABLE IF NOT EXISTS audiences (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE, -- e.g. "CS Majors"
    description VARCHAR(500)                  --can take away just so we can have description
);

CREATE TABLE IF NOT EXISTS events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- the database picks the next id
    event_title      VARCHAR(200) NOT NULL,
    host             VARCHAR(200) NOT NULL,
    event_date       DATE         NOT NULL,   -- "date" and "time" are SQL type names, so we prefix them
    event_time       TIME         NOT NULL,
    location         VARCHAR(200) NOT NULL,
    category         VARCHAR(50)  NOT NULL REFERENCES categories(name) ON UPDATE CASCADE, --need to link to category
    audience         VARCHAR(500) NOT NULL,
    format           VARCHAR(50)  NOT NULL,
    register_link    VARCHAR(500),            -- optional, can be NULL
    capacity         INT          NOT NULL DEFAULT 0, -- 0 = unlimited
    registered_count INT          NOT NULL DEFAULT 0, 
    -- Safety nets: the database itself refuses impossible numbers.
    CHECK (capacity >= 0),
    CHECK (registered_count >= 0),
    CHECK (capacity = 0 OR registered_count <= capacity)
);

-- event_audiences: which audiences each event is for.
-- One event can have MANY audiences, and one audience has MANY events
-- (a "many-to-many" relationship), so it needs its own table of pairs
-- will help us with calendar to filter events in next sprints
CREATE TABLE IF NOT EXISTS event_audiences (
    --       hold event ID CANT BE NULL bc need event in event table              
    event_id    BIGINT NOT NULL REFERENCES events(id)    ON DELETE CASCADE, -- deleting an event removes its links
    audience_id BIGINT NOT NULL REFERENCES audiences(id) ON DELETE CASCADE, -- deleting an audience removes its links
    PRIMARY KEY (event_id, audience_id) -- each pair only once (data.sql's ON CONFLICT relies on this)
);
-- ---------------------------------------------------------------------------
-- registrations: one row per "student X registered for event Y".
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS registrations (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id   BIGINT    NOT NULL REFERENCES events(id) ON DELETE CASCADE, -- must be a real event; deleting the event deletes its registrations
    user_id    BIGINT    NOT NULL,            -- the user's id from Shared Core (their table, not ours)
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (event_id, user_id)                -- the same student can't register twice for one event
);

-- ---------------------------------------------------------------------------
-- Resources: one row per career resource.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS resource (
	id			BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	user_id		BIGINT NOT NULL REFERENCES,
	owner		VARCHAR(200) NOT NULL,
	link		VARCHAR(500),				  -- optional, can be NULL
	status      VARCHAR(20)  NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected'))
);

-- ---------------------------------------------------------------------------
-- Opportunities: one row per career opportunity.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS opportunity (
	id			BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	title		VARCHAR(200) NOT NULL,
	date_posted DATE         NOT NULL,
	deadline	DATE		 NOT NULL,
	employer	VARCHAR(200) NOT NULL,
	link		VARCHAR(500) NOT NULL
);

-- ---------------------------------------------------------------------------
-- Audience_events/resource/opportunity: one row per audience relation.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS resource_audience (
	resource_id BIGINT NOT NULL REFERENCES resource(id) ON DELETE CASCADE,
	audience_id BIGINT NOT NULL REFERENCES audience(id) ON DELETE CASCADE,
	PRIMARY KEY (resource_id, audience_id)
);

CREATE TABLE IF NOT EXISTS opportunity_audience (
	opportunity_id BIGINT NOT NULL REFERENCES opportunity(id) ON DELETE CASCADE,
	audience_id BIGINT NOT NULL REFERENCES audience(id) ON DELETE CASCADE,
	PRIMARY KEY (opportunity_id, audience_id)
);